"""SQLAlchemy ORM model for the ``trades`` table."""

import uuid
from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import TYPE_CHECKING, Optional

from sqlalchemy import (
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    CURRENCY_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    SYMBOL_MAX_LENGTH,
)
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.account import Account
    from app.models.playbook import Playbook
    from app.models.tag import Tag
    from app.models.trade_note import TradeNote
    from app.models.user import User


class Direction(StrEnum):
    """Trade direction — long (buy) or short (sell)."""

    LONG = "LONG"
    SHORT = "SHORT"


class AssetClass(StrEnum):
    """Asset class of the traded instrument."""

    EQUITY = "EQUITY"
    OPTION = "OPTION"
    FUTURE = "FUTURE"
    FOREX = "FOREX"
    CRYPTO = "CRYPTO"


class Trade(Base):
    """ORM representation of a single trading position.

    This table is converted to a TimescaleDB hypertable partitioned by
    ``opened_at`` via the Alembic initial migration.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key to the :class:`~app.models.user.User` who owns
            this trade.  Used for direct user-scoped queries without requiring
            a join on ``accounts``.
        symbol: Ticker symbol (e.g. ``"AAPL"``, ``"ES"``).
        direction: Whether the position is long or short.
        asset_class: Asset class of the instrument.
        quantity: Number of units / contracts / shares traded.
        entry_price: Price at which the position was opened.
        exit_price: Price at which the position was closed
            (``None`` while still open).
        stop_loss: Optional stop-loss price level.
        take_profit: Optional take-profit price level.
        opened_at: Timestamp when the position was opened (partition key).
        closed_at: Timestamp when the position was closed
            (``None`` while still open).
        pnl: Realised profit or loss (``None`` while still open).
        commission: Total commission paid; defaults to zero.
        notes: Free-text notes attached to the trade.
        currency: ISO-4217 currency code of the trade (e.g. ``"USD"``).
            ``None`` for legacy trades that pre-date the EUR-reporting feature.
        pnl_eur: Realised P&L converted to EUR at the official Bundesbank
            daily rate on the trade date.  ``None`` for open trades, legacy
            trades, or when the exchange rate could not be determined.
        account_id: Foreign key to the :class:`~app.models.account.Account`
            that this trade belongs to (``None`` if not assigned to an account).
        account: The related :class:`~app.models.account.Account` ORM instance
            (``None`` if ``account_id`` is unset).
        playbook_id: Optional foreign key to the
            :class:`~app.models.playbook.Playbook` used for this trade.
        playbook: The related :class:`~app.models.playbook.Playbook` ORM
            instance (``None`` if no playbook assigned).
        tags: Many-to-many collection of :class:`~app.models.tag.Tag` objects
            attached to this trade via the ``trade_tags`` association table.
        trade_notes: One-to-many collection of
            :class:`~app.models.trade_note.TradeNote` objects.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by the database.
    """

    __tablename__ = "trades"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    symbol: Mapped[str] = mapped_column(
        String(SYMBOL_MAX_LENGTH),
        nullable=False,
    )
    direction: Mapped[Direction] = mapped_column(
        Enum(Direction, name="direction_enum"),
        nullable=False,
    )
    asset_class: Mapped[AssetClass] = mapped_column(
        Enum(AssetClass, name="asset_class_enum"),
        nullable=False,
    )
    quantity: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
    )
    entry_price: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
    )
    exit_price: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
    )
    stop_loss: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
    )
    take_profit: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
    )
    opened_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )
    closed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )
    pnl: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
    )
    commission: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
        server_default="0",
    )
    notes: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )
    tradingview_link: Mapped[str | None] = mapped_column(
        String,
        nullable=True,
    )
    screenshots: Mapped[list[str] | None] = mapped_column(
        JSONB,
        nullable=True,
        server_default="[]",
    )
    broker_order_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
        index=True,
        comment="External broker order identifier for deduplication.",
    )
    currency: Mapped[str | None] = mapped_column(
        String(CURRENCY_LENGTH),
        nullable=True,
        comment="ISO-4217 currency code of the trade (e.g. USD).",
    )
    pnl_eur: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
        comment=(
            "Realised P&L converted to EUR at the Bundesbank daily rate "
            "on the trade date."
        ),
    )
    account_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    playbook_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("playbooks.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_trades_symbol", "symbol"),
        Index("ix_trades_opened_at", "opened_at"),
        Index("ix_trades_closed_at", "closed_at"),
        Index("ix_trades_user_id", "user_id"),
        Index("ix_trades_account_id", "account_id"),
        Index("ix_trades_playbook_id", "playbook_id"),
        Index("ix_trades_broker_order_id", "broker_order_id"),
    )

    # Relationships
    user: Mapped[Optional["User"]] = relationship(
        "User",
        back_populates="trades",
    )
    account: Mapped[Optional["Account"]] = relationship(
        "Account",
        back_populates="trades",
    )
    playbook: Mapped[Optional["Playbook"]] = relationship(
        "Playbook",
        back_populates="trades",
    )
    tags: Mapped[list["Tag"]] = relationship(
        "Tag",
        secondary="trade_tags",
        back_populates="trades",
        lazy="selectin",
    )
    trade_notes: Mapped[list["TradeNote"]] = relationship(
        "TradeNote",
        back_populates="trade",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the trade.

        Returns:
            A debug string containing the id, symbol, and direction.
        """
        return f"<Trade id={self.id} symbol={self.symbol!r} direction={self.direction}>"
