"""SQLAlchemy ORM model for the ``playbooks`` table."""

import uuid
from datetime import datetime
from decimal import Decimal
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, CheckConstraint, DateTime, ForeignKey, Index, Numeric, String, Text, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import PLAYBOOK_NAME_MAX_LENGTH
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.playbook_attachment import PlaybookAttachment
    from app.models.playbook_link import PlaybookLink
    from app.models.playbook_taxonomy import PlaybookTaxonomy
    from app.models.trade import Trade


class Playbook(Base):
    """ORM representation of a trading playbook (strategy / setup type).

    A playbook is a named strategy that a user can attach to trades in order
    to group and analyse trades by their setup type.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key pointing to the owning user.
        name: Human-readable playbook name (unique per user).
        description: Optional long-form markdown content of the setup.
        is_active: Soft-disable flag; inactive playbooks can still be read
            but are hidden from selection in the UI by convention.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by a DB trigger.
        trades: Related :class:`~app.models.trade.Trade` objects that use
            this playbook.
    """

    __tablename__ = "playbooks"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(
        String(PLAYBOOK_NAME_MAX_LENGTH),
        nullable=False,
    )
    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )
    target_winrate: Mapped[Decimal | None] = mapped_column(
        Numeric(5, 4),
        nullable=True,
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_playbooks_user_id", "user_id"),
        Index("ix_playbooks_user_id_name", "user_id", "name", unique=True),
        CheckConstraint(
            "target_winrate >= 0 AND target_winrate <= 1",
            name="chk_playbooks_target_winrate",
        ),
    )

    # Relationships
    trades: Mapped[list["Trade"]] = relationship(
        "Trade",
        back_populates="playbook",
    )
    taxonomy_assignments: Mapped[list["PlaybookTaxonomy"]] = relationship(
        "PlaybookTaxonomy",
        back_populates="playbook",
        passive_deletes=True,
    )
    attachments: Mapped[list["PlaybookAttachment"]] = relationship(
        "PlaybookAttachment",
        back_populates="playbook",
        passive_deletes=True,
        order_by="PlaybookAttachment.created_at.asc()",
    )
    links: Mapped[list["PlaybookLink"]] = relationship(
        "PlaybookLink",
        back_populates="playbook",
        passive_deletes=True,
        order_by="PlaybookLink.created_at.asc()",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the playbook.

        Returns:
            A debug string containing the id and name.
        """
        return f"<Playbook id={self.id} name={self.name!r}>"
