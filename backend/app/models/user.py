"""SQLAlchemy ORM model for the ``users`` table."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, DateTime, Index, Integer, String, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.account import Account
    from app.models.broker_raw_transaction import BrokerRawTransaction
    from app.models.corporate_action import CorporateAction
    from app.models.daily_checkin import DailyCheckin
    from app.models.logical_execution import LogicalExecution
    from app.models.market_index import MarketIndexDefinition
    from app.models.pat import PersonalAccessToken
    from app.models.portfolio import Portfolio
    from app.models.saved_dashboard_view import SavedDashboardView
    from app.models.saved_trade_filter import SavedTradeFilter
    from app.models.trade import Trade
    from app.models.user_setting import UserSetting


class User(Base):
    """ORM representation of a registered user.

    Attributes:
        id: UUID primary key generated by the database.
        username: Unique display name chosen at registration.
        email: Unique email address used for login.
        hashed_password: bcrypt-hashed password — never the plain text.
            ``None`` for OAuth-only accounts that have no local password.
        provider: Authentication provider — ``'local'`` for password-based
            accounts or ``'google'`` for Google OAuth accounts.
        provider_id: Provider-specific user identifier (e.g. Google ``sub``
            claim). ``None`` for local accounts.
        is_active: Soft-disable flag; inactive users cannot authenticate.
        refresh_token_version: Monotonically incrementing counter used to
            invalidate all outstanding refresh tokens for this user.
            Incrementing this value (e.g. on logout) causes all previously
            issued refresh tokens to be rejected.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by a DB trigger.
        accounts: Related :class:`~app.models.account.Account` objects
            owned by this user.
        trades: All :class:`~app.models.trade.Trade` objects owned directly
            by this user (independent of account association).
        corporate_actions: All :class:`~app.models.corporate_action.CorporateAction`
            records owned by this user.
    """

    __tablename__ = "users"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    username: Mapped[str] = mapped_column(
        String(50),
        unique=True,
        nullable=False,
    )
    email: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        nullable=False,
    )
    hashed_password: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )
    provider: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="local",
        server_default="local",
    )
    provider_id: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
    )
    refresh_token_version: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        server_default="0",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    # Relationships
    accounts: Mapped[list["Account"]] = relationship(
        "Account",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    portfolios: Mapped[list["Portfolio"]] = relationship(
        "Portfolio",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    trades: Mapped[list["Trade"]] = relationship(
        "Trade",
        back_populates="user",
    )
    saved_trade_filters: Mapped[list["SavedTradeFilter"]] = relationship(
        "SavedTradeFilter",
        back_populates="owner",
        cascade="all, delete-orphan",
    )
    saved_dashboard_views: Mapped[list["SavedDashboardView"]] = relationship(
        "SavedDashboardView",
        back_populates="owner",
        cascade="all, delete-orphan",
    )
    settings: Mapped[list["UserSetting"]] = relationship(
        "UserSetting",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    corporate_actions: Mapped[list["CorporateAction"]] = relationship(
        "CorporateAction",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    broker_raw_transactions: Mapped[list["BrokerRawTransaction"]] = relationship(
        "BrokerRawTransaction",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    logical_executions: Mapped[list["LogicalExecution"]] = relationship(
        "LogicalExecution",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    market_indices: Mapped[list["MarketIndexDefinition"]] = relationship(
        "MarketIndexDefinition",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    daily_checkins: Mapped[list["DailyCheckin"]] = relationship(
        "DailyCheckin",
        back_populates="user",
        cascade="all, delete-orphan",
    )
    personal_access_tokens: Mapped[list["PersonalAccessToken"]] = relationship(
        "PersonalAccessToken",
        back_populates="owner",
        cascade="all, delete-orphan",
    )

    __table_args__ = (
        Index("ix_users_username", "username", unique=True),
        Index("ix_users_email", "email", unique=True),
        Index(
            "ix_users_provider_provider_id",
            "provider",
            "provider_id",
            unique=True,
            postgresql_where=text("provider_id IS NOT NULL"),
        ),
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the user.

        Returns:
            A debug string containing the id and username.
        """
        return f"<User id={self.id} username={self.username!r}>"
