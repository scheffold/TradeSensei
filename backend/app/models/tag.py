"""SQLAlchemy ORM model for the ``tags`` table."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Index, String, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import TAG_NAME_MAX_LENGTH
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.trade import Trade


class Tag(Base):
    """ORM representation of a user-defined trade tag.

    Tags provide a flexible labelling system; a user may attach multiple
    tags to any trade to categorise it by setup type, market condition,
    error type, or any other custom dimension.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key pointing to the owning user.
        name: Tag label (unique per user, case-sensitive).
        color: Optional hex colour string for UI display (e.g. ``"#3b82f6"``).
        created_at: Row-creation timestamp set by the database.
        trades: Related :class:`~app.models.trade.Trade` objects that carry
            this tag (many-to-many via ``trade_tags``).
    """

    __tablename__ = "tags"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(
        String(TAG_NAME_MAX_LENGTH),
        nullable=False,
    )
    color: Mapped[str | None] = mapped_column(
        String(7),  # e.g. "#3b82f6"
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    __table_args__ = (
        Index("ix_tags_user_id", "user_id"),
        Index("ix_tags_user_id_name", "user_id", "name", unique=True),
    )

    # Relationships
    trades: Mapped[list["Trade"]] = relationship(
        "Trade",
        secondary="trade_tags",
        back_populates="tags",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the tag.

        Returns:
            A debug string containing the id and name.
        """
        return f"<Tag id={self.id} name={self.name!r}>"
