"""SQLAlchemy ORM model for the ``account_properties`` table.

Stores encrypted key-value pairs of broker credentials tied to a specific
:class:`~app.models.account.Account`.  Each account may have multiple
properties (e.g. ``SCHWAB_APP_KEY``, ``SCHWAB_APP_SECRET``, etc.).
"""

import uuid
from typing import TYPE_CHECKING

from sqlalchemy import ForeignKey, Index, String, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import ACCOUNT_PROPERTY_KEY_MAX_LENGTH
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.account import Account


class AccountProperty(Base):
    """ORM representation of an encrypted account credential property.

    Each row stores a single key-value pair for an account.  Values are
    always Fernet-encrypted before storage and must be decrypted by the
    service layer before use.

    Attributes:
        id: UUID primary key generated by the database.
        account_id: Foreign key pointing to the owning
            :class:`~app.models.account.Account`.
        key: Property key identifier (e.g. ``"SCHWAB_APP_KEY"``).
        value: Fernet-encrypted property value.
        account: Parent :class:`~app.models.account.Account` relationship.
    """

    __tablename__ = "account_properties"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    key: Mapped[str] = mapped_column(
        String(ACCOUNT_PROPERTY_KEY_MAX_LENGTH),
        nullable=False,
        comment=("Property key identifier, e.g. 'SCHWAB_APP_KEY', 'SCHWAB_APP_SECRET', 'IBKR_FLEX_TOKEN', 'IBKR_FLEX_QUERY_ID'."),
    )
    value: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment="Fernet-encrypted property value.",
    )

    __table_args__ = (
        UniqueConstraint(
            "account_id",
            "key",
            name="uq_account_properties_account_key",
        ),
        Index("ix_account_properties_account_id", "account_id"),
    )

    # Relationships
    account: Mapped["Account"] = relationship(
        "Account",
        back_populates="properties",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the property.

        Returns:
            A debug string containing the id, account_id, and key.
        """
        return f"<AccountProperty id={self.id} account_id={self.account_id} key={self.key!r}>"
