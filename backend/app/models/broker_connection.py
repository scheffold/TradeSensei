"""SQLAlchemy ORM model for the ``broker_connections`` table."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Index, String, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.user import User


class BrokerConnection(Base):
    """ORM representation of a user's broker OAuth connection.

    Stores encrypted OAuth 2.0 tokens for a specific broker per user.
    The unique constraint on ``(user_id, broker)`` ensures each user can have
    at most one active connection per broker at a time.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: UUID of the owning user; foreign key to ``users.id``.
        broker: Broker identifier string (e.g. ``"schwab"``).
        access_token: Fernet-encrypted OAuth access token.
        refresh_token: Fernet-encrypted OAuth refresh token.
        token_expires_at: UTC timestamp when the access token expires.
        last_sync_at: UTC timestamp of the most recent successful trade sync.
            ``None`` if no sync has been performed yet.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by SQLAlchemy.
        user: Relationship back to the owning :class:`~app.models.user.User`.
    """

    __tablename__ = "broker_connections"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    broker: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
    )
    access_token: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment="Fernet-encrypted OAuth access token.",
    )
    refresh_token: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment="Fernet-encrypted OAuth refresh token.",
    )
    token_expires_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="UTC expiry timestamp of the access token.",
    )
    last_sync_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="UTC timestamp of the last successful trade sync.",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "broker",
            name="uq_broker_connections_user_broker",
        ),
        Index("ix_broker_connections_user_id", "user_id"),
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        foreign_keys="BrokerConnection.user_id",
        primaryjoin="BrokerConnection.user_id == User.id",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation.

        Returns:
            A debug string containing the id, user_id, and broker.
        """
        return (
            f"<BrokerConnection id={self.id} "
            f"user_id={self.user_id} broker={self.broker!r}>"
        )
