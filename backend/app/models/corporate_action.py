"""SQLAlchemy ORM model for the ``corporate_actions`` table."""

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import TYPE_CHECKING, Optional

from sqlalchemy import Date, DateTime, ForeignKey, Index, Numeric, String, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    SYMBOL_MAX_LENGTH,
)
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.user import User

CONID_MAX_LENGTH: int = 50
"""Maximum length for a broker contract identifier (conid)."""


class CorporateAction(Base):
    """ORM representation of a corporate action (stock split / reverse split).

    Corporate actions are user-scoped events that describe a ratio change
    for a given symbol on a given date.  They are used by the FIFO aggregator
    to adjust open lots chronologically so that post-split closing executions
    can be matched correctly.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key to the :class:`~app.models.user.User` who owns
            this record.
        symbol: Ticker symbol the action applies to (e.g. ``"OTLK"``).
        date: Calendar date on which the split took effect.
        ratio: Split ratio expressed as a :class:`Decimal`.
            For a 2:1 forward split ``ratio = 2.0`` (each share becomes two).
            For a 1:20 reverse split ``ratio = 0.05`` (twenty shares become one).
        old_conid: Optional broker contract ID *before* the split (IBKR conid).
            Used to re-key the aggregator queue when the broker assigns a new
            instrument identifier after the split.
        new_conid: Optional broker contract ID *after* the split.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by the database.
        user: Parent :class:`~app.models.user.User` relationship.
    """

    __tablename__ = "corporate_actions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    symbol: Mapped[str] = mapped_column(
        String(SYMBOL_MAX_LENGTH),
        nullable=False,
    )
    date: Mapped[date] = mapped_column(
        Date,
        nullable=False,
    )
    ratio: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
        comment=("Split ratio: >1 for a forward split (e.g. 2.0 = 2:1), <1 for a reverse split (e.g. 0.05 = 1:20)."),
    )
    old_conid: Mapped[str | None] = mapped_column(
        String(CONID_MAX_LENGTH),
        nullable=True,
        comment="Broker contract ID before the split (IBKR-specific).",
    )
    new_conid: Mapped[str | None] = mapped_column(
        String(CONID_MAX_LENGTH),
        nullable=True,
        comment="Broker contract ID after the split (IBKR-specific).",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        UniqueConstraint("user_id", "symbol", "date", name="uq_corporate_actions_user_symbol_date"),
        Index("ix_corporate_actions_user_id", "user_id"),
        Index("ix_corporate_actions_symbol", "symbol"),
        Index("ix_corporate_actions_date", "date"),
    )

    # Relationships
    user: Mapped[Optional["User"]] = relationship(
        "User",
        back_populates="corporate_actions",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation.

        Returns:
            A debug string with id, symbol, date, and ratio.
        """
        return f"<CorporateAction id={self.id} symbol={self.symbol!r} date={self.date} ratio={self.ratio}>"
