"""SQLAlchemy ORM model for the ``saved_trade_filters`` table."""

import uuid
from datetime import datetime
from enum import StrEnum
from typing import TYPE_CHECKING, Any, Optional

from sqlalchemy import (
    Boolean,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    String,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.user import User


class FilterScope(StrEnum):
    """Scope of the saved filter — system (global) or user-owned."""

    SYSTEM = "SYSTEM"
    USER = "USER"


class SavedTradeFilter(Base):
    """ORM representation of a persisted trade filter definition.

    Attributes:
        id: UUID primary key generated by the database.
        name: Display name of the filter.
        scope: Scope of the filter (system or user).
        definition: JSONB payload containing the filter query parameters.
        owner_id: Foreign key to the :class:`~app.models.user.User` who owns
            this filter (None for system filters).
        needs_review: Boolean flag indicating if the filter definition is
            invalid or references deprecated fields and requires user review.
        created_at: Row-creation timestamp.
        updated_at: Row-update timestamp.
    """

    __tablename__ = "saved_trade_filters"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )
    scope: Mapped[FilterScope] = mapped_column(
        Enum(FilterScope, name="filter_scope_enum"),
        nullable=False,
    )
    definition: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        server_default="{}",
    )
    owner_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=True,
        index=True,
    )
    needs_review: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        server_default="false",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_saved_trade_filters_scope", "scope"),
        Index("ix_saved_trade_filters_owner_id", "owner_id"),
    )

    # Relationships
    owner: Mapped[Optional["User"]] = relationship(
        "User",
        back_populates="saved_trade_filters",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the filter.

        Returns:
            A debug string containing the id, name, and scope.
        """
        return f"<SavedTradeFilter id={self.id} name={self.name!r} scope={self.scope}>"
