"""SQLAlchemy ORM model for the ``user_settings`` table.

Stores per-user UI preferences as key-value pairs.
"""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Index, String, Text, UniqueConstraint, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.database import Base

if TYPE_CHECKING:
    from app.models.user import User


class UserSetting(Base):
    """ORM representation of a per-user UI preference entry.

    Each row stores one key-value pair for a user. The unique constraint
    on ``(user_id, key)`` ensures at most one value per key per user.

    Supported keys and their valid values:
    - ``theme``: ``"system"``, ``"light"``, or ``"dark"``
    - ``default_date_range``: ``"all"``, ``"ytd"``, or ``"last30"``

    Attributes:
        id: UUID primary key generated by the database.
        user_id: UUID of the owning user; foreign key to ``users.id``.
        key: Setting key identifier (e.g. ``"theme"``).
        value: Setting value stored as text (e.g. ``"dark"``).
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by SQLAlchemy.
        user: Relationship back to the owning :class:`~app.models.user.User`.
    """

    __tablename__ = "user_settings"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    key: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        comment="Setting key identifier (e.g. 'theme', 'default_date_range').",
    )
    value: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        comment="Setting value stored as text.",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        UniqueConstraint(
            "user_id",
            "key",
            name="uq_user_settings_user_key",
        ),
        Index("ix_user_settings_user_id", "user_id"),
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        back_populates="settings",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation.

        Returns:
            A debug string containing the user_id and key.
        """
        return f"<UserSetting user_id={self.user_id} key={self.key!r}>"
