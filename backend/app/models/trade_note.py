"""SQLAlchemy ORM model for the ``trade_notes`` table."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Index, String, Text, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import EMOTION_MAX_LENGTH
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.trade import Trade


class TradeNote(Base):
    """ORM representation of a psychological / post-trade note on a trade.

    Multiple notes can be attached to a single trade to record the trader's
    mental state, observations, or post-trade review at different moments in
    time.

    Attributes:
        id: UUID primary key generated by the database.
        trade_id: Foreign key to ``trades.id``; cascades on delete.
        user_id: Foreign key to ``users.id``; cascades on delete.
        content: The body of the note (up to 10 000 characters).
        emotion: Optional emotion label (e.g. ``"fearful"``, ``"confident"``).
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by a DB trigger.
        trade: The parent :class:`~app.models.trade.Trade` ORM instance.
    """

    __tablename__ = "trade_notes"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    trade_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("trades.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    emotion: Mapped[str | None] = mapped_column(
        String(EMOTION_MAX_LENGTH),
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_trade_notes_trade_id", "trade_id"),
        Index("ix_trade_notes_user_id", "user_id"),
    )

    # Relationships
    trade: Mapped["Trade"] = relationship(
        "Trade",
        back_populates="trade_notes",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation of the trade note.

        Returns:
            A debug string containing the id and trade_id.
        """
        return f"<TradeNote id={self.id} trade_id={self.trade_id}>"
