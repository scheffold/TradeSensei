"""SQLAlchemy ORM model for the ``accounts`` table."""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import Boolean, DateTime, ForeignKey, Index, String, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    ACCOUNT_NAME_MAX_LENGTH,
    CURRENCY_LENGTH,
)
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.trade import Trade
    from app.models.user import User


class Account(Base):
    """ORM representation of a broker trading account.

    Each account belongs to exactly one :class:`~app.models.user.User`
    and can hold many :class:`~app.models.trade.Trade` entries.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key pointing to the owning :class:`~app.models.user.User`.
        name: Human-readable account name (e.g. "Interactive Brokers Main").
        broker: Optional broker identifier (e.g. "IBKR", "Schwab").
        currency: ISO-4217 currency code for the account (e.g. "USD").
        is_active: Soft-disable flag.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by a DB trigger.
        user: Parent :class:`~app.models.user.User` relationship.
        trades: Related :class:`~app.models.trade.Trade` objects for this account.
    """

    __tablename__ = "accounts"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(
        String(ACCOUNT_NAME_MAX_LENGTH),
        nullable=False,
    )
    broker: Mapped[str | None] = mapped_column(
        String(50),
        nullable=True,
    )
    currency: Mapped[str] = mapped_column(
        String(CURRENCY_LENGTH),
        nullable=False,
        default="USD",
        server_default="USD",
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        back_populates="accounts",
    )
    trades: Mapped[list["Trade"]] = relationship(
        "Trade",
        back_populates="account",
    )

    __table_args__ = (Index("ix_accounts_user_id", "user_id"),)

    def __repr__(self) -> str:
        """Return a human-readable string representation of the account.

        Returns:
            A debug string containing the id and name.
        """
        return f"<Account id={self.id} name={self.name!r}>"
