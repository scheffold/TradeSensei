"""SQLAlchemy ORM model for the ``accounts`` table."""

import uuid
from datetime import datetime
from enum import StrEnum
from typing import TYPE_CHECKING, Any

from sqlalchemy import Boolean, DateTime, ForeignKey, Index, String, func
from sqlalchemy import Enum as SAEnum
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    ACCOUNT_NAME_MAX_LENGTH,
    ACCOUNT_NUMBER_MAX_LENGTH,
    CURRENCY_LENGTH,
)
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.account_property import AccountProperty
    from app.models.broker_raw_transaction import BrokerRawTransaction
    from app.models.cash_transaction import CashTransaction
    from app.models.logical_execution import LogicalExecution
    from app.models.trade import Trade
    from app.models.user import User


class AccountType(StrEnum):
    """Enumeration of supported account/broker types.

    Attributes:
        MANUAL: A manually managed account with no live API connection.
        SCHWAB: A Charles Schwab brokerage account using the Schwab API.
        IBKR: An Interactive Brokers account using the IBKR Flex service.
    """

    MANUAL = "manual"
    SCHWAB = "schwab"
    IBKR = "ibkr"


class Account(Base):
    """ORM representation of a broker trading account.

    Each account belongs to exactly one :class:`~app.models.user.User`
    and can hold many :class:`~app.models.trade.Trade` entries.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key pointing to the owning :class:`~app.models.user.User`.
        name: Human-readable account name (e.g. "Interactive Brokers Main").
        account_number: Optional broker account number (e.g. "U1234567").
        type: Account/broker type (MANUAL, SCHWAB, or IBKR).
        currency: ISO-4217 currency code for the account (e.g. "USD").
        is_active: Soft-disable flag.
        settings: Optional JSONB blob storing per-account import/sync preferences
            such as ``sync_days``, ``flex_from_date_preset``, and
            ``flex_custom_from_date``.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by a DB trigger.
        user: Parent :class:`~app.models.user.User` relationship.
        trades: Related :class:`~app.models.trade.Trade` objects for this account.
        properties: Related :class:`~app.models.account_property.AccountProperty`
            key-value pairs storing encrypted broker credentials.
        broker_raw_transactions: Raw broker executions imported for this account.
        logical_executions: Logical execution records derived from raw data for
            this account.
    """

    __tablename__ = "accounts"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    name: Mapped[str] = mapped_column(
        String(ACCOUNT_NAME_MAX_LENGTH),
        nullable=False,
    )
    account_number: Mapped[str | None] = mapped_column(
        String(ACCOUNT_NUMBER_MAX_LENGTH),
        nullable=True,
    )
    type: Mapped[AccountType] = mapped_column(
        SAEnum(
            AccountType,
            name="accounttype",
            create_type=False,
            values_callable=lambda x: [e.value for e in x],
        ),
        nullable=False,
        default=AccountType.MANUAL,
        server_default=AccountType.MANUAL.value,
    )
    currency: Mapped[str] = mapped_column(
        String(CURRENCY_LENGTH),
        nullable=False,
        default="USD",
        server_default="USD",
    )
    is_active: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
        server_default="true",
    )
    settings: Mapped[dict[str, Any] | None] = mapped_column(
        JSONB,
        nullable=True,
        default=None,
        comment=(
            "Per-account import/sync settings stored as JSON. "
            "Keys: sync_days (int), flex_from_date_preset (str), "
            "flex_custom_from_date (str YYYYMMDD or null)."
        ),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    # Relationships
    user: Mapped["User"] = relationship(
        "User",
        back_populates="accounts",
    )
    trades: Mapped[list["Trade"]] = relationship(
        "Trade",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    cash_transactions: Mapped[list["CashTransaction"]] = relationship(
        "CashTransaction",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    properties: Mapped[list["AccountProperty"]] = relationship(
        "AccountProperty",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    broker_raw_transactions: Mapped[list["BrokerRawTransaction"]] = relationship(
        "BrokerRawTransaction",
        back_populates="account",
        cascade="all, delete-orphan",
    )
    logical_executions: Mapped[list["LogicalExecution"]] = relationship(
        "LogicalExecution",
        back_populates="account",
        cascade="all, delete-orphan",
    )

    __table_args__ = (Index("ix_accounts_user_id", "user_id"),)

    def __repr__(self) -> str:
        """Return a human-readable string representation of the account.

        Returns:
            A debug string containing the id, name, and type.
        """
        return f"<Account id={self.id} name={self.name!r} type={self.type.value}>"
