"""SQLAlchemy ORM model for the ``logical_executions`` table.

The logical layer is the application's mutable view of executions.  An
initial logical execution is created 1:1 from each :class:`BrokerRawTransaction`
with ``origin = 'imported'``.  Users (or automated processes like corporate
action handling) may later split, merge, or manually create logical executions
while the underlying raw transactions remain untouched.

Each logical execution is eventually linked to a :class:`~app.models.trade.Trade`
once the FIFO aggregator has matched it into a round-trip position.

Design decision: the ``origin`` field is immutable — set once at creation and
never patchable by API consumers.  The ``deleted`` and ``user_modified`` flags
are the two mutable state dimensions.

Origin values:
- ``imported``: Created 1:1 from a BrokerRawTransaction.
- ``manual``: Created by the user without a broker raw transaction.
- ``merged``: Created by merging two or more executions.
- ``split``: Created by splitting a single execution into two.
"""

import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import TYPE_CHECKING, Optional

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Numeric,
    String,
    Text,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    CURRENCY_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    SYMBOL_MAX_LENGTH,
)
from app.core.database import Base
from app.models.trade import AssetClass, Direction

if TYPE_CHECKING:
    from app.models.account import Account
    from app.models.broker_raw_transaction import BrokerRawTransaction
    from app.models.trade import Trade
    from app.models.user import User

CONID_MAX_LENGTH: int = 50
"""Maximum length for a broker contract identifier (conid)."""

EXECUTION_ORIGIN_IMPORTED: str = "imported"
EXECUTION_ORIGIN_MANUAL: str = "manual"
EXECUTION_ORIGIN_MERGED: str = "merged"
EXECUTION_ORIGIN_SPLIT: str = "split"

VALID_ORIGINS: frozenset[str] = frozenset(
    [
        EXECUTION_ORIGIN_IMPORTED,
        EXECUTION_ORIGIN_MANUAL,
        EXECUTION_ORIGIN_MERGED,
        EXECUTION_ORIGIN_SPLIT,
    ]
)
"""Valid values for the ``origin`` field (matches CHECK constraint in DB)."""


class LogicalExecution(Base):
    """Mutable application-level representation of a single execution leg.

    This table sits between the immutable raw broker data and the aggregated
    :class:`~app.models.trade.Trade` records.  The aggregator reads
    exclusively from this table (filtered by ``deleted=false``) so that user
    manipulations (merges, splits, manual entries, soft-deletes) are reflected
    in the final trade history without losing the original broker data.

    Attributes:
        id: UUID primary key generated by the database.
        user_id: Foreign key to the owning :class:`~app.models.user.User`.
        account_id: Optional foreign key to the associated
            :class:`~app.models.account.Account`.
        symbol: Ticker symbol (may differ from the raw transaction after a
            corporate action remap).
        conid: Broker contract identifier, or ``None``.
        asset_class: Asset class of the traded instrument.
        direction: Buy (LONG) or sell (SHORT) side of the execution.
        quantity: Execution quantity (absolute, always positive).
        price: Execution price per unit.
        commission: Commission for this execution leg.
        executed_at: Timestamp of the execution in UTC.
        pnl: Broker-reported realised P&L (``None`` for opening legs).
        pnl_eur: Realised P&L converted to EUR (``None`` if not available).
        currency: ISO-4217 currency code (e.g. ``"USD"``).
        multiplier: Contract multiplier (1 for equities, >1 for futures/options).
        origin: Immutable provenance flag — one of ``imported``, ``manual``,
            ``merged``, or ``split``.  Set once at creation, never changed.
        deleted: Soft-delete flag.  When ``True``, excluded from aggregation.
            ``imported``, ``merged``, and ``split`` executions are soft-deleted;
            ``manual`` executions are hard-deleted.
        user_modified: ``True`` when the user has patched an ``imported``,
            ``split``, or ``merged`` execution.  Set automatically by the
            service layer.  Never reset.  ``manual`` executions are never
            marked — they are user-owned by construction.
        parent_id: Optional FK to the original execution for split/merge lineage.
        trade_id: Optional foreign key to the
            :class:`~app.models.trade.Trade` produced after aggregation.
            ``None`` until the aggregator assigns this execution to a trade.
        raw_transactions: Many-to-many collection of
            :class:`~app.models.broker_raw_transaction.BrokerRawTransaction`
            objects linked via the ``transaction_execution_mappings`` junction
            table.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by the database.
    """

    __tablename__ = "logical_executions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    account_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    symbol: Mapped[str] = mapped_column(
        String(SYMBOL_MAX_LENGTH),
        nullable=False,
    )
    conid: Mapped[str | None] = mapped_column(
        String(CONID_MAX_LENGTH),
        nullable=True,
        comment="Broker contract identifier (IBKR conid).",
    )
    asset_class: Mapped[AssetClass] = mapped_column(
        Enum(AssetClass, name="asset_class_enum", create_type=False),
        nullable=False,
    )
    direction: Mapped[Direction] = mapped_column(
        Enum(Direction, name="direction_enum", create_type=False),
        nullable=False,
    )
    quantity: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
        comment="Execution quantity (absolute, always positive).",
    )
    price: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
        comment="Execution price per unit.",
    )
    commission: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
        server_default="0",
        comment="Commission for this execution leg.",
    )
    executed_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        comment="Timestamp of the execution (UTC).",
    )
    pnl: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
        comment="Broker-reported realised P&L (None for opening legs).",
    )
    pnl_eur: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
        comment="Realised P&L converted to EUR at the Bundesbank daily rate.",
    )
    multiplier: Mapped[int] = mapped_column(
        nullable=False,
        server_default="1",
        comment="Contract multiplier (1 for equities, >1 for futures/options).",
    )
    currency: Mapped[str | None] = mapped_column(
        String(CURRENCY_LENGTH),
        nullable=True,
        comment="ISO-4217 currency code (e.g. 'USD').",
    )
    origin: Mapped[str] = mapped_column(
        Text(),
        nullable=False,
        server_default=EXECUTION_ORIGIN_IMPORTED,
        comment="Immutable provenance: imported | manual | merged | split.",
    )
    deleted: Mapped[bool] = mapped_column(
        Boolean(),
        nullable=False,
        server_default="false",
        comment="Soft-delete flag. When True, excluded from FIFO aggregation.",
    )
    user_modified: Mapped[bool] = mapped_column(
        Boolean(),
        nullable=False,
        server_default="false",
        comment=("True when user patched an imported, split, or merged execution. Never reset."),
    )
    is_mixed_execution: Mapped[bool] = mapped_column(
        Boolean(),
        nullable=False,
        server_default="false",
        comment=(
            "True when the broker reported a position flip (C;O or O;C) for this"
            " execution.  The FIFO aggregator uses this to allow the closing portion"
            " to leave a new open lot rather than treating the remainder as orphaned."
        ),
    )
    open_close: Mapped[str | None] = mapped_column(
        String(1),
        nullable=True,
        comment=(
            "Opening/closing indicator derived by the broker parser: 'O' (opening),"
            " 'C' (closing), or NULL (mixed/unknown/manual). Populated from IBKR"
            " openCloseIndicator or Schwab positionEffect."
        ),
    )
    strike: Mapped[Decimal | None] = mapped_column(
        Numeric(18, 8),
        nullable=True,
        comment="Option strike price derived from OCC symbol.",
    )
    expiry: Mapped[date | None] = mapped_column(
        Date,
        nullable=True,
        comment="Option expiry date derived from OCC symbol.",
    )
    option_type: Mapped[str | None] = mapped_column(
        String(1),
        nullable=True,
        comment="Option type derived from OCC symbol: 'C' or 'P'.",
    )
    source_id: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
        index=True,
        comment=(
            "Original broker raw transaction ID (e.g. 'ibkr:3820422546')."
            " Used as a stable tie-breaker when multiple executions share the"
            " same executed_at timestamp, matching the broker-native sort order."
        ),
    )
    parent_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("logical_executions.id", ondelete="SET NULL"),
        nullable=True,
        comment="Lineage FK: points to original execution for split/merge.",
    )
    trade_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("trades.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        comment=("Aggregated Trade this execution was assigned to. None until the aggregator runs."),
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_le_user_id", "user_id"),
        Index("ix_le_account_id", "account_id"),
        Index("ix_le_symbol", "symbol"),
        Index("ix_le_executed_at", "executed_at"),
        Index("ix_le_conid", "conid"),
        Index("ix_le_origin", "origin"),
        Index("ix_le_trade_id", "trade_id"),
        Index("ix_le_trade_id_deleted", "trade_id", "deleted"),
        Index("ix_le_parent_id", "parent_id"),
        Index(
            "uix_le_source_id",
            "source_id",
            unique=True,
            postgresql_where=text("source_id IS NOT NULL"),
        ),
    )

    # Relationships
    user: Mapped[Optional["User"]] = relationship(
        "User",
        back_populates="logical_executions",
    )
    account: Mapped[Optional["Account"]] = relationship(
        "Account",
        back_populates="logical_executions",
    )
    trade: Mapped[Optional["Trade"]] = relationship(
        "Trade",
        back_populates="logical_executions",
    )
    raw_transactions: Mapped[list["BrokerRawTransaction"]] = relationship(
        "BrokerRawTransaction",
        secondary="transaction_execution_mappings",
        back_populates="logical_executions",
        lazy="selectin",
    )
    parent: Mapped[Optional["LogicalExecution"]] = relationship(
        "LogicalExecution",
        foreign_keys=[parent_id],
        remote_side="LogicalExecution.id",
        back_populates="children",
    )
    children: Mapped[list["LogicalExecution"]] = relationship(
        "LogicalExecution",
        foreign_keys=[parent_id],
        back_populates="parent",
    )

    def __repr__(self) -> str:
        """Return a debug string for this logical execution.

        Returns:
            A string with id, symbol, direction, quantity, origin, and deleted.
        """
        return (
            f"<LogicalExecution id={self.id} symbol={self.symbol!r} direction={self.direction} qty={self.quantity} origin={self.origin} deleted={self.deleted}>"
        )
