"""SQLAlchemy ORM model for the ``cash_transactions`` table."""

import uuid
from datetime import datetime
from decimal import Decimal
from enum import StrEnum
from typing import TYPE_CHECKING

from sqlalchemy import (
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Numeric,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.core.constants import (
    CURRENCY_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    SYMBOL_MAX_LENGTH,
)
from app.core.database import Base

if TYPE_CHECKING:
    from app.models.account import Account


class CashTransactionType(StrEnum):
    """Types of non-trade cash flows."""

    DIVIDEND = "DIVIDEND"
    WITHHOLDING_TAX = "WITHHOLDING_TAX"
    DEPOSIT = "DEPOSIT"
    WITHDRAWAL = "WITHDRAWAL"
    INTEREST = "INTEREST"
    FEE = "FEE"
    OTHER = "OTHER"


class CashTransaction(Base):
    """ORM representation of a non-trade cash flow.

    Attributes:
        id: UUID primary key generated by the database.
        account_id: Foreign key to the :class:`~app.models.account.Account`
            that this cash transaction belongs to.
        date: Timestamp of the transaction.
        type: The categorization of the transaction.
        symbol: Optional related asset symbol (e.g. "AAPL" for a dividend).
        amount: Raw amount in the transaction's native currency.
        currency: ISO-4217 currency code of the transaction (e.g. "USD").
        amount_eur: The amount converted to EUR at the Bundesbank daily rate.
        description: Free-text description of the transaction.
        created_at: Row-creation timestamp set by the database.
        updated_at: Row-update timestamp maintained by the database.
        account: The related :class:`~app.models.account.Account` ORM instance.
    """

    __tablename__ = "cash_transactions"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=func.gen_random_uuid(),
    )
    account_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("accounts.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        primary_key=True,
        nullable=False,
    )
    type: Mapped[CashTransactionType] = mapped_column(
        Enum(CashTransactionType, name="cash_transaction_type_enum"),
        nullable=False,
    )
    symbol: Mapped[str | None] = mapped_column(
        String(SYMBOL_MAX_LENGTH),
        nullable=True,
    )
    amount: Mapped[Decimal] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=False,
    )
    currency: Mapped[str] = mapped_column(
        String(CURRENCY_LENGTH),
        nullable=False,
    )
    amount_eur: Mapped[Decimal | None] = mapped_column(
        Numeric(NUMERIC_PRECISION, NUMERIC_SCALE),
        nullable=True,
        comment=(
            "Amount converted to EUR at the Bundesbank daily rate "
            "on the transaction date."
        ),
    )
    description: Mapped[str | None] = mapped_column(
        Text,
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )

    __table_args__ = (
        Index("ix_cash_transactions_date", "date"),
        Index("ix_cash_transactions_account_id_date", "account_id", "date"),
        Index("ix_cash_transactions_type", "type"),
    )

    # Relationships
    account: Mapped["Account"] = relationship(
        "Account",
        back_populates="cash_transactions",
    )

    def __repr__(self) -> str:
        """Return a human-readable string representation."""
        return (
            f"<CashTransaction id={self.id} type={self.type} "
            f"amount={self.amount} {self.currency}>"
        )
